// Builds native/ui/emoji_data.cpp, the emoji the keyboard offers, from Unicode's emoji-test.txt (kept
// beside this script; https://www.unicode.org/Public/emoji/latest/emoji-test.txt, Unicode's terms of use
// allow it): every fully-qualified emoji without a skin tone, in Unicode's (CLDR's) order and groups,
// with its name, the words it is found by and, for those that take one, its five skin-tone forms (each
// person in the same tone). Which of them a Y1 shows is decided there, by what its emoji font draws.
//   node tools/emoji/make-list.cjs [emoji-test.txt] [out.cpp]
const fs = require("fs");
const path = require("path");
const src = process.argv[2] || path.join(__dirname, "emoji-test.txt");
const out = process.argv[3] || path.join(__dirname, "../../native/ui/emoji_data.cpp");
const lines = fs.readFileSync(src, "utf8").split("\n");
const version = (lines.find((l) => l.startsWith("# Version:")) || "").replace("# Version:", "").trim();

// Unicode's groups as the keyboard's tabs (0 is Recent); Component (the bare skin tones, hair) is left out
const GROUPS = { "Smileys & Emotion": 1, "People & Body": 2, "Animals & Nature": 3, "Food & Drink": 4, "Travel & Places": 5, Activities: 6, Objects: 7, Symbols: 8, Flags: 9 };
const isTone = (cp) => cp >= 0x1f3fb && cp <= 0x1f3ff;
// what an emoji is without its tones and emoji-form selectors (🖐️ and 🖐🏽 are the same hand)
const bare = (cps) => cps.filter((c) => !isTone(c) && c !== 0xfe0f).join(" ");
// the words a name or a subgroup is found by: lower case, accents and punctuation gone
const words = (s) => s.normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase().replace(/[’']/g, "").split(/[^a-z0-9]+/).filter(Boolean);

let group = 0, subgroup = "";
const list = [], byBare = new Map();
const tones = new Map();  // bare -> [5 forms]
for (const l of lines) {
  let m = l.match(/^# group: (.*)$/);
  if (m) { group = GROUPS[m[1].trim()] || 0; continue; }
  m = l.match(/^# subgroup: (.*)$/);
  if (m) { subgroup = m[1].trim(); continue; }
  m = l.match(/^([0-9A-F ]+?)\s*;\s*fully-qualified\s*#\s*\S+\s+E[\d.]+\s+(.*)$/);
  if (!m || !group) continue;
  const cps = m[1].trim().split(/\s+/).map((h) => parseInt(h, 16));
  const text = String.fromCodePoint(...cps);
  const t = cps.filter(isTone);
  if (!t.length) {
    const e = { text, name: m[2].trim(), group, subgroup };
    list.push(e);
    byBare.set(bare(cps), e);
    continue;
  }
  if (t.some((x) => x !== t[0])) continue;  // people in different tones: not offered (one tone for all)
  const key = bare(cps);
  if (!tones.has(key)) tones.set(key, []);
  tones.get(key)[t[0] - 0x1f3fb] = text;
}
for (const [key, forms] of tones) {
  const e = byBare.get(key);
  if (!e || forms.filter(Boolean).length !== 5) throw new Error(`tones without their emoji: ${key}`);
  e.tones = forms;
}

// C string literals: printable ASCII as it is, every other byte as a three-digit octal escape
const c = (s) => '"' + [...Buffer.from(s, "utf8")].map((b) => (b >= 0x20 && b < 0x7f && b !== 0x22 && b !== 0x5c && b !== 0x3f ? String.fromCharCode(b) : "\\" + b.toString(8).padStart(3, "0"))).join("") + '"';
const display = (n) => n.charAt(0).toUpperCase() + n.slice(1);

let toneRows = [], body = [];
for (const e of list) {
  const name = words(e.name).join(" ");
  const sub = words(e.subgroup).filter((w) => !name.split(" ").includes(w)).join(" ");
  let tone = 0;
  if (e.tones) toneRows.push(`    {${e.tones.map(c).join(", ")}},`), (tone = toneRows.length);
  body.push(`    {${c(e.text)}, ${c(display(e.name))}, ${c(sub ? `${name}|${sub}` : name)}, ${e.group}, ${tone}},`);
}
const counts = {};
for (const e of list) counts[e.group] = (counts[e.group] || 0) + 1;

const cpp = `// Generated by tools/emoji/make-list.cjs from tools/emoji/emoji-test.txt (Unicode Emoji ${version}): don't
// edit, run the script again. ${list.length} emoji, ${toneRows.length} of them with skin tones.
#include "emoji.h"

namespace rondo::ui::emoji {

const Info kList[] = {
${body.join("\n")}
};
const int kCount = ${list.length};

// each toned emoji's five forms, light to dark (Info::tone is its row + 1)
const char* const kTones[][5] = {
${toneRows.join("\n")}
};

}  // namespace rondo::ui::emoji
`;
fs.writeFileSync(out, cpp);
console.log(`emoji: ${list.length} (${Object.values(counts).join(" + ")}), ${toneRows.length} with tones, Unicode ${version} -> ${path.relative(process.cwd(), out)}`);
