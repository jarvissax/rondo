static void testPlaces() {
  // channel art from image/url only as a fallback (here after the items); an item's itunes:image is the item's
  Result r = parse(
      "<rss><channel><title>T</title><item><itunes:image href=\"https://e/item.jpg\"/><enclosure url=\"https://e/a.mp3\"/></item>"
      "<image><url> https://e/fallback.jpg </url></image></channel></rss>");
  CHECK(r.ok && r.eps.size() == 1);
  CHECK_EQ(r.ch.art, "https://e/fallback.jpg");
  if (r.eps.size() == 1) {
    CHECK_EQ(r.eps[0].image, "https://e/item.jpg");
    CHECK_EQ(r.eps[0].type, "audio/mpeg");
  }
  // items only directly in channel; channel fields only directly under it
  r = parse(
      "<rss><channel><foo:list><item><enclosure url=\"https://e/no.mp3\"/></item><title>No</title></foo:list>"
      "<item><title>Yes</title><enclosure url=\"https://e/yes.mp3\"/><foo:x><title>No</title></foo:x></item>"
      "<itunes:author>Author</itunes:author><managingEditor>Editor</managingEditor></channel>"
      "<item><enclosure url=\"https://e/outside.mp3\"/></item></rss>");
  CHECK(r.ok && r.eps.size() == 1);
  CHECK_EQ(r.ch.title, "");
  CHECK_EQ(r.ch.author, "Author");
  if (r.eps.size() == 1) CHECK_EQ(r.eps[0].title, "Yes");
  // missing closing tags: an item not closed before the next; the feed cut short in an item (that one
  // doesn't count, as on the server); a feed without </channel></rss> at its end
  const char* cut =
      "<rss><channel><title>Cut</title><item><title>One</title><enclosure url=\"https://e/1.mp3\"/>"
      "<item><title>Two</title><enclosure url=\"https://e/2.mp3\"/></item>"
      "<item><title>Three</title><enclosure url=\"https://e/3.mp3\"/><description>Notes &amp; more";
  r = parse(cut);
  CHECK(r.ok && r.eps.size() == 2);
  CHECK_EQ(r.ch.title, "Cut");
  if (r.eps.size() == 2) {
    CHECK_EQ(r.eps[0].title, "One");
    CHECK_EQ(r.eps[1].title, "Two");
  }
  checkChunking(cut, "a feed cut short");
  r = parse("<rss><channel><title>Open</title><item><enclosure url=\"https://e/1.mp3\"/></item>");
  CHECK(r.ok && r.eps.size() == 1);
  // HTML written into a description without CDATA, a title missing its end tag
  r = parse(
      "<rss><channel><item><enclosure url=\"https://e/1.mp3\"/><description>Hello <b>bold</b> &amp; <br> next</description>"
      "</item><item><title>Unclosed<enclosure url=\"https://e/2.mp3\"/></item></channel></rss>");
  CHECK(r.ok && r.eps.size() == 1);
  if (!r.eps.empty()) CHECK_EQ(r.eps[0].notes, "Hello bold &\nnext");
  // whitespace and a UTF-8 BOM before the declaration
  r = parse("\xEF\xBB\xBF\n\n<?xml version='1.0'?>\n<rss><channel><title>BOM</title></channel></rss>");
  CHECK(r.ok);
  CHECK_EQ(r.ch.title, "BOM");
  // the description from itunes:summary before description; managingEditor when there's nothing else
  r = parse(
      "<rss><channel><description>Plain</description><itunes:summary>Summary</itunes:summary><managingEditor>ed@x (Ed)"
      "</managingEditor><itunes:explicit>clean</itunes:explicit><itunes:type>episodic</itunes:type></channel></rss>");
  CHECK_EQ(r.ch.description, "Summary");
  CHECK_EQ(r.ch.author, "ed@x (Ed)");
  CHECK(!r.ch.explicitContent && !r.ch.serial && !r.ch.complete);
  // unknown episode types are full; season and episode numbers with spaces
  r = parse(
      "<rss><channel><item><enclosure url='https://e/1.mp3'/><itunes:episodeType>Weird</itunes:episodeType>"
      "<itunes:season> 04 </itunes:season><itunes:episode>x</itunes:episode></item></channel></rss>");
  if (r.eps.size() == 1) {
    CHECK_EQ(r.eps[0].episodeType, "full");
    CHECK_EQ(r.eps[0].season, 4);
    CHECK_EQ(r.eps[0].number, 0);
  } else {
    CHECK(false);
  }
}

static void testEncodings() {
  // windows-1252: “Café” – Olé €
  std::string w =
      "<?xml version=\"1.0\" encoding=\"windows-1252\"?><rss><channel><title>\x93" "Caf\xe9\x94 \x96 Ol\xe9 \x80</title>"
      "<item><title>Na\xefve</title><enclosure url=\"https://e/\xe9.mp3\"/></item></channel></rss>";
  Result r = parse(w);
  CHECK(r.ok);
  CHECK_EQ(r.ch.title, "\xE2\x80\x9C" "Caf\xC3\xA9\xE2\x80\x9D \xE2\x80\x93 Ol\xC3\xA9 \xE2\x82\xAC");
  if (r.eps.size() == 1) {
    CHECK_EQ(r.eps[0].title, "Na\xC3\xAFve");
    CHECK_EQ(r.eps[0].url, "https://e/\xC3\xA9.mp3");
  } else {
    CHECK(false);
  }
  checkChunking(w, "a windows-1252 feed");
  // ISO-8859-1 in single quotes
  r = parse("<?xml version='1.0' encoding='ISO-8859-1' ?><rss><channel><title>Espa\xf1ol</title></channel></rss>");
  CHECK_EQ(r.ch.title, "Espa\xC3\xB1ol");
  // any other encoding is read as UTF-8: bad bytes become U+FFFD, control characters go
  r = parse("<?xml version=\"1.0\" encoding=\"iso-8859-15\"?><rss><channel><title>bad \xff byte\x01 \xe2\x82 cut</title>"
            "<link>https://e/\x7f" "x</link></channel></rss>");
  CHECK_EQ(r.ch.title, "bad \xEF\xBF\xBD byte \xEF\xBF\xBD cut");
  CHECK_EQ(r.ch.link, "https://e/x");
  // UTF-8 cut anywhere still comes out whole
  std::string u = "<rss><channel><title>\xE6\x97\xA5\xE6\x9C\xAC \xF0\x9F\x8E\xA7 caf\xC3\xA9</title></channel></rss>";
  CHECK_EQ(parse(u, 1).ch.title, "\xE6\x97\xA5\xE6\x9C\xAC \xF0\x9F\x8E\xA7 caf\xC3\xA9");
  // numeric references are code points (&#147; is a control character, dropped)
  CHECK_EQ(parse("<rss><channel><title>&#147;Hi&#148; &#8211; &#x2014;</title></channel></rss>").ch.title,
           "Hi \xE2\x80\x93 \xE2\x80\x94");
}

static void testNotFeeds() {
  auto refused = [](const std::string& s) {
    Result r = parse(s);
    return !r.ok && r.eps.empty();
  };
  // an HTML page: clear at its DOCTYPE, or at its first element
  Result r = parse("<!DOCTYPE html>\n<html><head><title>Not found</title></head><body><p>404</p></body></html>");
  CHECK(!r.fed && !r.ok);
  r = parse("<html><body><rss><channel><title>x</title></channel></rss></body></html>");
  CHECK(!r.fed && !r.ok);
  // an Atom feed
  r = parse(
      "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n<feed xmlns=\"http://www.w3.org/2005/Atom\"><title>Atom</title>"
      "<entry><title>x</title><link rel=\"enclosure\" href=\"https://e/a.mp3\"/></entry></feed>");
  CHECK(!r.fed && !r.ok);
  // not XML at all
  CHECK(!parse("{\"version\": \"https://jsonfeed.org/version/1\"}").fed);
  CHECK(!parse("Hello, no markup at all").ok);
  // text before the first element (a PHP notice, say) is passed over, as the server does
  r = parse("Notice: something\n<?xml version=\"1.0\"?><rss><channel><title>T</title></channel></rss>");
  CHECK(r.fed && r.ok);
  CHECK(refused(""));
  CHECK(refused("   \n "));
  CHECK(refused(std::string("\xFF\xFE<\0r\0s\0s\0>\0", 12)));  // UTF-16
  // RSS without a channel
  r = parse("<rss version=\"2.0\"></rss>");
  CHECK(r.fed && !r.ok);
  CHECK(refused("<rss/>"));
  // the byte-by-byte answer is the same
  CHECK(!parse("<!DOCTYPE html><html></html>", 1).fed);
  CHECK(!parse("<?xml version=\"1.0\"?><feed></feed>", 1).fed);
}

static void testGarbage() {
  std::string base = "<rss><channel><title>G</title>";
  auto done = [](const Result& r) { return r.ok; };
  // unterminated CDATA, comment, tag; deep nesting; a long run with no '>'; random bytes
  CHECK(done(parse(base + "<item><description><![CDATA[never ends")));
  CHECK(done(parse(base + "<!-- never ends")));
  CHECK(done(parse(base + "<item><enclosure url=\"https://e/a.mp3\"")));
  std::string deep = base;
  for (int i = 0; i < 20000; i++) deep += "<a>";
  deep += "text";
  for (int i = 0; i < 20000; i++) deep += "</a>";
  deep += "<item><enclosure url=\"https://e/after.mp3\"/></item></channel></rss>";
  Result r = parse(deep);
  CHECK(r.ok && r.eps.size() == 1);
  std::string longTag = base + "<foo " + std::string(200000, 'x') + "<item><enclosure url=\"https://e/b.mp3\"/></item></channel></rss>";
  r = parse(longTag);
  CHECK(r.ok && r.eps.size() == 1);
  CHECK_EQ(dump(parse(longTag, 777, 3)), dump(r));
  std::mt19937 rng(42);
  for (int round = 0; round < 200; round++) {
    std::string g = base;
    size_t n = rng() % 4000;
    static const char pieces[][12] = {"<", ">", "&", ";", "<item>", "</item>", "<![CDATA[", "]]>", "<!--", "-->", "\"", "'",
                                      "=", "<enclosure", " url=", "&#x", "&amp", "/>", "<?", "?>", "<!", "</"};
    for (size_t i = 0; i < n; i++) {
      unsigned k = rng() % 30;
      if (k < 22) g += pieces[k];
      else g += char(rng() % 256);
    }
    Result whole = parse(g);
    if (dump(parse(g, 13, round + 1)) != dump(whole)) {
      fprintf(stderr, "%s:%d: FAILED: chunking changes garbage round %d\n", __FILE__, __LINE__, round);
      failures++;
      break;
    }
  }
}

static void testDates() {
  const long long t = 1730802600;  // 2024-11-05 10:30:00 UTC
  CHECK_EQ((long long)parseDate("Tue, 05 Nov 2024 10:30:00 +0000"), t);
  CHECK_EQ((long long)parseDate("05 Nov 2024 10:30:00 +0000"), t);           // no weekday
  CHECK_EQ((long long)parseDate("Tue, 5 Nov 2024 10:30:00 GMT"), t);         // single-digit day
  CHECK_EQ((long long)parseDate("Tue, 05 Nov 24 10:30:00 GMT"), t);          // 2-digit year
  CHECK_EQ((long long)parseDate("Tue, 05 Nov 2024 12:30:00 +0200"), t);      // +hhmm
  CHECK_EQ((long long)parseDate("Tue, 05 Nov 2024 12:30:00 +02:00"), t);     // +hh:mm
  CHECK_EQ((long long)parseDate("Tue, 05 Nov 2024 02:30:00 -0800"), t);      // -hhmm
  CHECK_EQ((long long)parseDate("Tue, 05 Nov 2024 05:30:00 EST"), t);
  CHECK_EQ((long long)parseDate("Tue, 05 Nov 2024 03:30:00 PDT"), t);
  CHECK_EQ((long long)parseDate("Tue, 05 Nov 2024 04:30:00 CST"), t);
  CHECK_EQ((long long)parseDate("Tue, 05 Nov 2024 10:30:00 UT"), t);
  CHECK_EQ((long long)parseDate("Tue, 05 Nov 2024 10:30:00 UTC"), t);
  CHECK_EQ((long long)parseDate("Tue, 05 Nov 2024 10:30:00 Z"), t);
  CHECK_EQ((long long)parseDate("Tue, 05 Nov 2024 10:30:00"), t);            // no zone: UTC
  CHECK_EQ((long long)parseDate("Tue, 05 Nov 2024 10:30:00 XYZ"), t);        // unknown zone: UTC
  CHECK_EQ((long long)parseDate("Tue, 05 Nov 2024 10:30 +0000"), t);         // no seconds
  CHECK_EQ((long long)parseDate("  tue, 05 NOV 2024 10:30:00 gmt  "), t);    // any case, spaces
  CHECK_EQ((long long)parseDate("Tuesday, 05 November 2024 10:30:00 GMT"), t);
  CHECK_EQ((long long)parseDate("Tue, 05 Nov 2024 10:30:00 GMT+0100"), t);  // a zone not on the list: UTC
  CHECK_EQ((long long)parseDate("Tue,05 Nov 2024 10:30:00 +0000"), t);
  CHECK_EQ((long long)parseDate("Thu, 05 Sept 2024 10:30:00 GMT"), 1725532200LL);  // "Sept"
  CHECK_EQ((long long)parseDate("2024-11-05T10:30:00Z"), t);
  CHECK_EQ((long long)parseDate("2024-11-05T12:30:00+02:00"), t);
  CHECK_EQ((long long)parseDate("2024-11-05T16:00:00+0530"), t);  // a zone without its colon
  CHECK_EQ((long long)parseDate("2024-11-05T12:30:00+02"), t);
  CHECK_EQ((long long)parseDate("2024-11-05T02:30:00-0800"), t);
  CHECK_EQ((long long)parseDate("2024-11-05T09:30:00.123-0100"), t);
  CHECK_EQ((long long)parseDate("2024-11-05T12:30 +02:00"), t);
  CHECK_EQ((long long)parseDate("Fri, 31 Dec 99 23:59:59 Z"), 946684799LL);
  CHECK_EQ((long long)parseDate("2024-11-05T10:30:00.123Z"), t);
  CHECK_EQ((long long)parseDate("2024-11-05 10:30:00"), t);
  CHECK_EQ((long long)parseDate("2024-11-05"), 1730764800LL);
  CHECK_EQ((long long)parseDate("Fri, 02 Jan 70 00:00:00 GMT"), 86400LL);  // 70: 1970
  CHECK_EQ((long long)parseDate("Thu, 01 Jan 69 00:00:00 GMT"), (long long)parseDate("2069-01-01"));
  CHECK_EQ((long long)parseDate("Wed, 29 Feb 2012 23:59:59 GMT"), 1330559999LL);
  // garbage
  for (const char* s : {"", "yesterday", "Tue, 32 Nov 2024 10:00:00 GMT", "Tue, 05 Foo 2024 10:30:00 GMT", "2024-13-01",
                        "2024/11/05", "Nov 05 2024", "05 Nov 2024 25:00:00 GMT", "05 Nov 202 10:00:00", "2024-11-05T10",
                        "1730802600", "Tue, 05 Nov 2024 10:3", "Tue, 05 Nov 2024", "01-Nov-2024 10:00:00", "2024-11-05T10:30:00+053",
                        "2024-11-05T10:30:00+05:", "2024-11-05T10:30.5Z", "Tue, 05 Nov 2024 10:30:00.000 GMT"})
    if (parseDate(s) != 0) {
      fprintf(stderr, "%s:%d: FAILED: parseDate(\"%s\") = %lld, want 0\n", __FILE__, __LINE__, s, (long long)parseDate(s));
      failures++;
    }
}

