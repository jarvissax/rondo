static void testPlainText() {
  CHECK_EQ(plainText("a<br>b<br/>c<BR />d", 100), "a\nb\nc\nd");
  CHECK_EQ(plainText("a<br>b", 100, true), "a b");
  CHECK_EQ(plainText("<p>One</p><p>Two</p>", 100), "One\nTwo");
  CHECK_EQ(plainText("<div>A</div><h2>B</h2><blockquote>C</blockquote>D", 100), "A\nB\nC\nD");
  CHECK_EQ(plainText("<ul><li>A</li><li>B</li></ul>", 100), "\xE2\x80\xA2 A\n\xE2\x80\xA2 B");
  CHECK_EQ(plainText("x<script type=\"text/javascript\">var a = '<p>';</script>y", 100), "xy");
  CHECK_EQ(plainText("<style>p { color: red }</style>Hi<SCRIPT>no()</SCRIPT>!", 100), "Hi!");
  CHECK_EQ(plainText("<b>bold</b> <i>it</i><span>s</span>", 100), "bold its");
  CHECK_EQ(plainText("<span class=\"a>b\">s</span>", 100), "b\">s");  // a tag ends at its first '>', as on the server
  CHECK_EQ(plainText("a</br>b<o:p>c</o:p><br_x>", 100), "abc<br_x>");
  CHECK_EQ(plainText("Tom &amp; Jerry &copy; &eacute;t&eacute; &#169; &#xA9; &#XA9; &unknown; AT&T &amp", 100),
           "Tom & Jerry \xC2\xA9 \xC3\xA9t\xC3\xA9 \xC2\xA9 \xC2\xA9 \xC2\xA9 &unknown; AT&T &amp");
  CHECK_EQ(plainText("&lt;b&gt;bold&lt;/b&gt;", 100), "<b>bold</b>");  // entities decoded after the tags are found
  CHECK_EQ(plainText("1 &nbsp; 2&nbsp;&nbsp;3", 100), "1 2 3");
  CHECK_EQ(plainText("  a \t  b  \n\n\n\n  c  ", 100), "a b\n\nc");
  CHECK_EQ(plainText("line  \n  next", 100), "line\nnext");
  CHECK_EQ(plainText("a\r\nb\rc", 100), "a\nb\nc");
  CHECK_EQ(plainText("Title\nwith\n\nbreaks", 100, true), "Title with breaks");
  CHECK_EQ(plainText("<!-- note -->x<?php ?>y", 100), "x<?php ?>y");
  CHECK_EQ(plainText("a < b, 1<2, <3", 100), "a < b, 1<2, <3");
  CHECK_EQ(plainText("text <a href=\"x", 100), "text <a href=\"x");  // a tag without its '>' is text
  CHECK_EQ(plainText("a\xff" "b \x01\x7f" "c", 100), "a\xEF\xBF\xBD" "b c");
  CHECK_EQ(plainText("", 100), "");
  CHECK_EQ(plainText("<p> </p><br>", 100), "");
  // the cut: at most maxBytes with the "…", never mid-character
  CHECK_EQ(plainText("abcdef", 6), "abcdef");
  CHECK_EQ(plainText("abcdefg", 6), "abc\xE2\x80\xA6");
  CHECK_EQ(plainText("aa\xC3\xA9\xC3\xA9\xC3\xA9", 6), "aa\xE2\x80\xA6");      // é straddles the cut: left out
  CHECK_EQ(plainText("a\xC3\xA9\xC3\xA9\xC3\xA9\xC3\xA9", 6), "a\xC3\xA9\xE2\x80\xA6");
  CHECK_EQ(plainText("word word word", 9), "word w\xE2\x80\xA6");
  CHECK_EQ(plainText("abcd efgh", 8), "abcd\xE2\x80\xA6");  // no space before the "…"
  CHECK_EQ(plainText("one<p>two</p>three", 100), "onetwo\nthree");
  std::string big;
  for (int i = 0; i < 3000; i++) big += "<p>Paragraph \xE6\x97\xA5 number " + std::to_string(i) + "</p>";
  std::string t = plainText(big, 4000);
  CHECK(t.size() <= 4000 && t.size() > 3990);
  CHECK(t.compare(t.size() - 3, 3, "\xE2\x80\xA6") == 0);
}

