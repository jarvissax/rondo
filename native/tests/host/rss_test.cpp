static void testBig() {
  std::string feed = bigFeed();
  using Clock = std::chrono::steady_clock;
  int n = 0;
  int64_t sizes = 0;
  size_t notes = 0;
  Channel ch;
  auto t0 = Clock::now();
  {
    Parser p([&](Episode&& e) {
      n++;
      sizes += e.size;
      notes += e.notes.size();
    });
    for (size_t i = 0; i < feed.size(); i += 16384) CHECK(p.feed(feed.data() + i, std::min<size_t>(16384, feed.size() - i)));
    CHECK(p.finish(ch));
  }
  double chunked = std::chrono::duration<double, std::milli>(Clock::now() - t0).count();
  auto t1 = Clock::now();
  Result whole = parse(feed);
  double all = std::chrono::duration<double, std::milli>(Clock::now() - t1).count();
  printf("rss: %.1f MB, %d items: %.1f ms in 16 KB chunks, %.1f ms whole\n", feed.size() / 1e6, n, chunked, all);
  CHECK_EQ(n, 2000);
  CHECK_EQ(whole.count, 2000);
  CHECK_EQ(ch.title, "Big Show");
  CHECK_EQ(ch.author, "Someone");
  CHECK(feed.size() > 9000000);
  CHECK(chunked < 1000);
  CHECK(notes > 2000 * 2000 && notes <= 2000 * 4000);
  CHECK_EQ((long long)sizes, 2000LL * 30000000 + 1999 * 1000);
  if (whole.eps.size() == 2000) {
    const Episode& e = whole.eps[1234];
    CHECK_EQ(e.title, "Episode 1234: A Title & a Subtitle");
    CHECK_EQ(e.url, "https://cdn.example.com/audio/episode-1234.mp3?source=feed&x=1");
    CHECK_EQ(e.number, 1234);
    CHECK_EQ(e.duration, 3723);
    std::string start = "In this episode we talk about things, other things & more \xE2\x80\x94 including caf\xC3\xA9s";
    CHECK(e.notes.compare(0, start.size(), start) == 0);
  }
}

