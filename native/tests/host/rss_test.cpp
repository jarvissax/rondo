static int failures = 0;
#define CHECK(cond)                                                      \
  do {                                                                   \
    if (!(cond)) {                                                       \
      fprintf(stderr, "%s:%d: FAILED: %s\n", __FILE__, __LINE__, #cond); \
      failures++;                                                        \
    }                                                                    \
  } while (0)
#define CHECK_EQ(a, b)                                                                                              \
  do {                                                                                                              \
    auto va = (a);                                                                                                  \
    auto vb = (b);                                                                                                  \
    if (!(va == vb)) {                                                                                              \
      fprintf(stderr, "%s:%d: FAILED: %s == %s\n  got:  [%s]\n  want: [%s]\n", __FILE__, __LINE__, #a, #b, show(va).c_str(), \
              show(vb).c_str());                                                                                    \
      failures++;                                                                                                   \
    }                                                                                                               \
  } while (0)

static std::string show(const std::string& s) { return s; }
static std::string show(const char* s) { return s; }
static std::string show(long long v) { return std::to_string(v); }
static std::string show(int v) { return std::to_string(v); }

struct Result {
  bool fed = true, ok = false;
  Channel ch;
  std::vector<Episode> eps;
  int count = 0;
};

// chunk 0: all at once; else pieces of 1..chunk bytes (random when seed isn't 0)
static Result parse(const std::string& xml, size_t chunk = 0, unsigned seed = 0) {
  Result r;
  Parser p([&](Episode&& e) { r.eps.push_back(std::move(e)); });
  std::mt19937 rng(seed);
  for (size_t i = 0; i < xml.size() && r.fed;) {
    size_t n = chunk == 0 ? xml.size() : seed ? 1 + rng() % chunk : chunk;
    n = std::min(n, xml.size() - i);
    r.fed = p.feed(xml.data() + i, n);
    i += n;
  }
  r.ok = p.finish(r.ch);
  r.count = p.count();
  return r;
}

static std::string dump(const Result& r) {
  std::string s = std::string(r.fed ? "fed " : "refused ") + (r.ok ? "ok\n" : "not a feed\n");
  const Channel& c = r.ch;
  s += c.title + "|" + c.author + "|" + c.description + "|" + c.art + "|" + c.link + "|" + c.language + "|" + c.newFeedUrl + "|" +
       (c.serial ? "S" : "-") + (c.explicitContent ? "E" : "-") + (c.complete ? "C" : "-") + "\n";
  for (const Episode& e : r.eps)
    s += e.guid + "|" + e.title + "|" + e.url + "|" + e.type + "|" + e.image + "|" + e.chapters + "|" + e.episodeType + "|" +
         e.notes + "|" + std::to_string(e.date) + "|" + std::to_string(e.size) + "|" + std::to_string(e.duration) + "|" +
         std::to_string(e.season) + "|" + std::to_string(e.number) + "\n";
  return s + std::to_string(r.count);
}

// the same feed whole, byte by byte and in random pieces gives the same
static void checkChunking(const std::string& xml, const char* what) {
  std::string whole = dump(parse(xml));
  bool same = dump(parse(xml, 1)) == whole;
  for (unsigned seed = 1; seed <= 25 && same; seed++) same = dump(parse(xml, seed % 5 == 0 ? 4096 : 97, seed)) == whole;
  if (!same) {
    fprintf(stderr, "%s:%d: FAILED: chunking changes the result of %s\n", __FILE__, __LINE__, what);
    failures++;
  }
}

